//! Membership keys claimed with an invite (`POST /membership/claim`).
//!
//! An invite holder that sets up an agent exchanges the invite for a membership
//! key of its own: a new credential for the member's principal, never the
//! member's original key. Each set-up names itself with a claim id it
//! generated and keeps; the server keeps `(invite id, hash(claim id)) ->
//! credential` in `membership_claims`, so the same set-up asking again gets
//! the same key, and a different set-up gets a credential of its own. Neither
//! revokes or replaces anything.
//!
//! The key is handed over the way an approved join request's is: a bounded
//! clear-text delivery copy, re-collectable until the set-up acknowledges it
//! (after verifying and storing the key) or until `CLAIM_DELIVERY_WINDOW_MS`
//! after the claim, whichever comes first. Both clear the copy through the
//! same `secure_delete` and owed-checkpoint machinery the join-request copy
//! uses (`expire_delivery_copies`).

use super::*;

/// How many set-ups one invite may claim a key for. Repeats of one set-up do
/// not count. Past it a set-up is refused and the Master re-issues the invite
/// (a new invite has a count of its own). It bounds what a leaked invite can
/// mint.
pub const MEMBERSHIP_CLAIMS_PER_INVITE: i64 = 5;

/// How long a claimed key stays re-collectable by its set-up: 24 hours from
/// the claim, the join-request window (`JOIN_BOOTSTRAP_WINDOW_MS`) for the
/// same reason. The kit collects, verifies, stores and acknowledges within
/// seconds; the window is for a set-up that crashed or lost its answer.
pub const CLAIM_DELIVERY_WINDOW_MS: u64 = JOIN_BOOTSTRAP_WINDOW_MS;

/// SQL that is true when a `membership_claims` row's delivery deadline has
/// passed at `:now` with the window in `:window`. A claim time that is
/// missing or not positive is taken as past, as for join requests.
pub(super) const PAST_CLAIM_DELIVERY_DEADLINE: &str =
    "(COALESCE(claimed_at, 0) <= 0 OR :now >= claimed_at + :window)";

/// The answer to a claim.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MemberClaim {
    /// The set-up's key. `fresh` when this call minted it; a repeat of the
    /// same set-up gets the same key with `fresh` false.
    Delivered {
        key: String,
        credential_id: String,
        fresh: bool,
    },
    /// This set-up acknowledged its key: the server no longer holds it, and
    /// nothing new is minted.
    AlreadyDelivered,
    /// This set-up never acknowledged its key and its delivery ended (the
    /// deadline passed, or the key was revoked first): nothing is minted.
    DeliveryEnded,
    /// The invite already has `MEMBERSHIP_CLAIMS_PER_INVITE` set-ups.
    CapReached,
}

impl Store {
    /// Claim a key for one set-up of the member an invite seats.
    ///
    /// `invite_id` is the invite's `ivid_`; `claim_hash` the hash of the
    /// set-up's claim id, `None` for a caller that sent none (an older kit:
    /// every such call is a new set-up, with no delivery copy and no retry).
    /// `key` is the key to mint if this is a new set-up, generated by the
    /// caller; it is stored as a hash in `credentials` and, for a set-up with
    /// a claim id, as the delivery copy. A storage error is an error, never
    /// one of the answers.
    pub fn claim_member_key(
        &self,
        invite_id: &str,
        claim_hash: Option<&str>,
        principal_id: &str,
        label: &str,
        key: &str,
        now: u64,
    ) -> rusqlite::Result<MemberClaim> {
        let Some(mut c) = self.conn() else {
            return Err(rusqlite::Error::InvalidQuery);
        };
        if let Some(claim_hash) = claim_hash {
            // The held connection guard spans this read and whatever follows,
            // so a concurrent repeat of the same set-up sees the row this one
            // writes and gets the same key.
            let row: Option<(String, Option<String>, bool, bool, bool)> = c
                .query_row(
                    &format!(
                        "SELECT m.credential_id, m.delivery_token, m.acked_at IS NOT NULL, \
                                {PAST_CLAIM_DELIVERY_DEADLINE}, c.revoked_at IS NOT NULL \
                         FROM membership_claims m JOIN credentials c ON c.id = m.credential_id \
                         WHERE m.invite_id = :invite AND m.claim_hash = :claim"
                    ),
                    rusqlite::named_params! {
                        ":invite": invite_id,
                        ":claim": claim_hash,
                        ":now": now,
                        ":window": CLAIM_DELIVERY_WINDOW_MS,
                    },
                    |r| Ok((r.get(0)?, r.get(1)?, r.get(2)?, r.get(3)?, r.get(4)?)),
                )
                .optional()?;
            if let Some((credential_id, copy, acked, past, revoked)) = row {
                if acked {
                    return Ok(MemberClaim::AlreadyDelivered);
                }
                let Some(copy) = copy else {
                    return Ok(MemberClaim::DeliveryEnded);
                };
                if past || revoked {
                    expire_delivery_copies(
                        &mut c,
                        now,
                        DeliveryCopies::Claim(invite_id, claim_hash),
                    )?;
                    settle_owed_checkpoint_logged(&c);
                    return Ok(MemberClaim::DeliveryEnded);
                }
                return Ok(MemberClaim::Delivered {
                    key: copy,
                    credential_id,
                    fresh: false,
                });
            }
        }
        let credential_id = hashed_id("cr_", &format!("credential:{key}"));
        // `secure_delete` for the inserts too: they can move other set-ups'
        // rows, delivery copies included, between pages.
        with_secure_delete(&mut c, |conn| {
            let tx = conn.transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)?;
            let count: i64 = tx.query_row(
                "SELECT COUNT(*) FROM membership_claims WHERE invite_id = ?1",
                params![invite_id],
                |r| r.get(0),
            )?;
            if count >= MEMBERSHIP_CLAIMS_PER_INVITE {
                return Ok(MemberClaim::CapReached);
            }
            tx.execute(
                "INSERT INTO credentials
                 (id, principal_id, label, secret_hash, created_at, last_used_at, revoked_at, legacy_source)
                 VALUES (?1, ?2, ?3, ?4, ?5, NULL, NULL, NULL)",
                params![credential_id, principal_id, label, secret_hash(key), now],
            )?;
            tx.execute(
                "INSERT INTO membership_claims
                 (credential_id, invite_id, claim_hash, claimed_at, delivery_token, acked_at, expired_at)
                 VALUES (?1, ?2, ?3, ?4, ?5, NULL, NULL)",
                params![
                    credential_id,
                    invite_id,
                    claim_hash,
                    now,
                    claim_hash.map(|_| key)
                ],
            )?;
            tx.commit()?;
            Ok(MemberClaim::Delivered {
                key: key.to_string(),
                credential_id: credential_id.clone(),
                fresh: true,
            })
        })
    }

    /// The set-up has verified its key and stored it: clear the delivery
    /// copy. `Some(true)` when this call recorded the ACK, `Some(false)` when
    /// the set-up had already acknowledged (a safe retry), `None` when no
    /// such set-up exists. Like the join-request ACK it also answers after
    /// the deadline: a set-up whose ACK was lost has done nothing wrong, and
    /// the cleared copy stays cleared. A storage error is an error.
    pub fn ack_member_claim(
        &self,
        invite_id: &str,
        claim_hash: &str,
        now: u64,
    ) -> rusqlite::Result<Option<bool>> {
        let Some(mut c) = self.conn() else {
            return Err(rusqlite::Error::InvalidQuery);
        };
        let row: Option<(Option<u64>, bool)> = c
            .query_row(
                "SELECT acked_at, delivery_token IS NOT NULL FROM membership_claims \
                 WHERE invite_id = ?1 AND claim_hash = ?2",
                params![invite_id, claim_hash],
                |r| Ok((r.get(0)?, r.get(1)?)),
            )
            .optional()?;
        let Some((acked_at, holds_copy)) = row else {
            return Ok(None);
        };
        if acked_at.is_some() {
            return Ok(Some(false));
        }
        let changed = with_secure_delete(&mut c, |conn| {
            let tx = conn.transaction()?;
            let changed = tx.execute(
                "UPDATE membership_claims SET acked_at = ?3, delivery_token = NULL \
                 WHERE invite_id = ?1 AND claim_hash = ?2 AND acked_at IS NULL",
                params![invite_id, claim_hash, now],
            )?;
            if holds_copy {
                record_owed_checkpoint(&tx)?;
            }
            tx.commit()?;
            Ok(changed)
        })?;
        if holds_copy {
            settle_owed_checkpoint_logged(&c);
        }
        Ok(Some(changed == 1))
    }

    /// Test-only: the set-up's stored delivery copy. `Some(Some(_))` while it
    /// is held, `Some(None)` once cleared, `None` when no such set-up exists.
    #[cfg(test)]
    pub fn member_claim_copy_raw(
        &self,
        invite_id: &str,
        claim_hash: &str,
    ) -> Option<Option<String>> {
        let c = self.conn()?;
        c.query_row(
            "SELECT delivery_token FROM membership_claims WHERE invite_id = ?1 AND claim_hash = ?2",
            params![invite_id, claim_hash],
            |r| r.get::<_, Option<String>>(0),
        )
        .ok()
    }

    /// Test-only: how many set-ups an invite has claimed a key for. `-1` when
    /// the count could not be read, which no expected count equals.
    #[cfg(test)]
    pub fn member_claim_count(&self, invite_id: &str) -> i64 {
        let Some(c) = self.conn() else { return -1 };
        c.query_row(
            "SELECT COUNT(*) FROM membership_claims WHERE invite_id = ?1",
            params![invite_id],
            |r| r.get(0),
        )
        .unwrap_or(-1)
    }
}
